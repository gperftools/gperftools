#!/usr/bin/env ruby
# Regenerates .github/workflows/ci.yml and ci/configs.json from ci/*.cue.
#
# Usage: ruby ci/gen.rb
#
# Needs the cue tool in PATH.

require 'open3'

CI_DIR = __dir__
WORKFLOW = File.join(CI_DIR, '..', '.github', 'workflows', 'ci.yml')
CONFIGS_JSON = File.join(CI_DIR, 'configs.json')
HEADER = "# GENERATED by ci/gen.rb -- DO NOT EDIT. Edit ci/*.cue and rerun ci/gen.rb.\n"

def cue_export(expr, format)
  out, status = Open3.capture2('cue', 'export', '-e', expr, '--out', format, '.', chdir: CI_DIR)
  abort "cue export -e #{expr} failed" unless status.success?
  out
end

# Write via a temp file so a failed run never leaves a half-written file.
def write(path, content)
  tmp = "#{path}.tmp"
  File.binwrite(tmp, content)
  File.rename(tmp, path)
end

write(WORKFLOW, HEADER + cue_export('workflow', 'yaml'))
write(CONFIGS_JSON, cue_export('runData', 'json'))
